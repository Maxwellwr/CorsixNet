using System.Collections.Frozen;

namespace CorsixNet.Formats;

/// <summary>
/// The code page used by the Western-language Theme Hospital bitmap fonts: code page 437,
/// with the box-drawing characters and a few others replaced by '?' because the
/// fonts do not contain them.
/// </summary>
public static class Cp437
{
    private const int Unmapped = '?';

    /// <summary>Unicode code points for bytes 0x80–0xFF.</summary>
    private static readonly ushort[] HighToUnicode =
    [
        0x00C7, 0x00FC, 0x00E9, 0x00E2, 0x00E4, 0x00E0, 0x00E5, 0x00E7,
        0x00EA, 0x00EB, 0x00E8, 0x00EF, 0x00EE, 0x00EC, 0x00C4, 0x00C5,
        0x00C9, 0x00E6, 0x003F, 0x00F4, 0x00F6, 0x00F2, 0x00FB, 0x00F9,
        0x00FF, 0x00D6, 0x00DC, 0x00A2, 0x00A3, 0x00A5, 0x20A7, 0x0192,
        0x00E1, 0x00ED, 0x00F3, 0x00FA, 0x00F1, 0x00D1, 0x00AA, 0x00BA,
        0x00BF, 0x2310, 0x00AC, 0x00BD, 0x00BC, 0x00A1, 0x00AB, 0x00BB,
        0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F,
        0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F,
        0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F,
        0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F,
        0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F,
        0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F, 0x003F,
        0x03B1, 0x00DF, 0x0393, 0x03C0, 0x03A3, 0x03C3, 0x03BC, 0x03C4,
        0x03A6, 0x0398, 0x03A9, 0x03B4, 0x221E, 0x03C6, 0x03B5, 0x2229,
        0x2261, 0x00B1, 0x2265, 0x2264, 0x2320, 0x2321, 0x00F7, 0x2248,
        0x00B0, 0x2219, 0x00B7, 0x221A, 0x207F, 0x00B2, 0x25A0, 0x00A0,
    ];

    private static readonly FrozenDictionary<int, byte> UnicodeToHigh = HighToUnicode
        .Select((codePoint, index) => (CodePoint: (int)codePoint, Byte: (byte)(0x80 + index)))
        .Where(pair => pair.CodePoint != Unmapped)
        .ToFrozenDictionary(pair => pair.CodePoint, pair => pair.Byte);

    /// <summary>Maps a Unicode code point to a font character code; unmapped characters become '?'.</summary>
    public static int FromUnicode(int codePoint)
    {
        if (codePoint < 0x80)
        {
            return codePoint;
        }

        return UnicodeToHigh.TryGetValue(codePoint, out var b) ? b : Unmapped;
    }

    /// <summary>Maps a font character code back to Unicode.</summary>
    public static int ToUnicode(byte code)
    {
        return code < 0x80 ? code : HighToUnicode[code - 0x80];
    }
}
